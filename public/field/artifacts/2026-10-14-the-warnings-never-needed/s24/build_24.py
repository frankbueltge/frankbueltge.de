"""Study 24: writes data_24.js for the page's section #s24 from data/results_24.json, data/met_24.tsv.gz
and the Studio's warnings (for example messages, 4 met and 4 unmet per class, seed 24).

Usage: python3 -I build_24.py STUDIO_DATA_JS
"""
import json, sys, gzip, csv, random, hashlib, collections
from pathlib import Path

HERE = Path(__file__).parent
raw = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest() == "3c6c369c5c57790b58b1ef8b3ec5be5718676b231c055fa363ae56e2107849ef"
s = raw.decode()
CARDS = json.loads(s[s.index("window.CARDS=") + 13:].strip().rstrip(";"))
res = json.loads((HERE / "data" / "results_24.json").read_text())
M = list(csv.DictReader(gzip.open(HERE / "data" / "met_24.tsv.gz", "rt"), delimiter="\t"))
W = list(csv.DictReader(gzip.open(HERE / "data" / "warnings_24.tsv.gz", "rt"), delimiter="\t"))
cut = 29583360  # 2026-04-01T00:00Z in minutes since 1970 (analyse_24.py FRAME_END)
pool = collections.Counter(w["status"] for w in W if w["group"] == "undeclared" and int(w["t_min"]) < cut)
assert sum(pool.values()) == res["undeclared_in_frame"] == 8948
und = [r for r in M if r["group"] == "undeclared"]
win = {k: sum(int(r[k]) for r in und) for k in ("met_strict", "met", "met_72")}
rnd = random.Random(24)
ex = {}
for c in ("fire", "flood", "severe", "winter"):
    out = []
    for flag in ("1", "0"):
        sel = [r for r in und if r["primary"] == c and r["met"] == flag]
        for r in rnd.sample(sel, 4):
            k = CARDS[int(r["i"])]
            out.append({"met": flag == "1", "placebo": r["placebo"] == "1", "code": k["c"], "w": k["w"][:160],
                        "places": k["p"][:2], "day": int(k["t"]) // 1440})
    ex[c] = out
keep = lambda v: {a: v[a] for a in ("n", "met", "met_rate", "met_ci", "placebo", "placebo_rate", "placebo_ci", "excess", "excess_ci", "strict_rate", "pad72_rate")}
D = {"pool": dict(pool), "pool_n": sum(pool.values()), "windows": win,
     "und": keep(res["undeclared_covered"]), "decl": keep(res["declared_contradicted"]),
     "classes": {c: keep(v) for c, v in res["by_class"].items()},
     "bound": res["bound_share"], "bound_ci": res["bound_share_ci"], "pred": res["predictions"],
     "unmapped": res["stats"]["events_unmapped"], "events": res["stats"]["events_in_classes"], "ex": ex}
(HERE / "data_24.js").write_text("// generated by build_24.py; FEMA IPAWS messages and NOAA Storm Events are public domain\nwindow.D24=" + json.dumps(D, separators=(",", ":")) + ";\n")
print(json.dumps({k: D[k] for k in ("pool", "pool_n", "windows", "bound")}))
