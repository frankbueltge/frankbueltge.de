"""Study 27: writes data_27.js for the page's section #s27 from data/*_27.* and the Studio's warnings.

The reasons given for the 19 unmet earthquake messages are my reading after the result (exploration,
not pre-registered), each backed by data/events_27.json, the yearly catalogue or data/explore_27.json.

Usage: python3 -I build_27.py STUDIO_DATA_JS
"""
import json, sys, gzip, csv, hashlib, random
from pathlib import Path

HERE = Path(__file__).parent
raw = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest() == "3c6c369c5c57790b58b1ef8b3ec5be5718676b231c055fa363ae56e2107849ef"
s = raw.decode()
CARDS = json.loads(s[s.index("window.CARDS=") + 13:].strip().rstrip(";"))
R = json.loads((HERE / "data" / "results_27.json").read_text())
A = json.loads((HERE / "data" / "audit_27.json").read_text())
EV = json.loads((HERE / "data" / "events_27.json").read_text())
J = list(csv.DictReader(gzip.open(HERE / "data" / "joined_27.tsv.gz", "rt"), delimiter="\t"))
H = list(csv.DictReader(open(HERE / "data" / "hand_27.tsv"), delimiter="\t"))
M = {r["i"]: r for r in csv.DictReader(gzip.open(HERE.parent / "s24" / "data" / "met_24.tsv.gz", "rt"), delimiter="\t")}
WHY = {}
for i in (2132, 2142, 2143, 2146, 2148, 2149):
    WHY[i] = "radius: M5.8 18 km SSE of Lone Pine (ci39493944), 140 km from the nearest named county's centre"
for i in (4964, 4966, 4967):
    WHY[i] = "radius: M4.92 7 km WNW of Rio Dell (nc73821046), 137 km from the nearest named county's centre"
WHY[7433] = "radius: M4.06 22 km SW of Lamont (ci40865224), 127 km away"
WHY[8377] = WHY[8378] = "radius: M3.2 20 km NNE of Yerington, Nevada (nn00888571), 134 km away"
WHY[9134] = "radius: M5.21 5 km S of Julian (ci40925991), 201 km away; an M3.54 at 181 km"
WHY[5404] = "box: M5.58 108 km W of Petrolia (nc73890906), offshore, outside the rule's contiguous-US box"
WHY[1668] = "a report, not an alert: it names an M5.0 near Mentone, Texas, about 280 km from El Paso"
WHY[1893] = "no earthquake: ComCat holds no event above M1.3 within 30 minutes in eastern California"
WHY[1894] = "the sender's own cancel of the alert before it"
WHY[10607] = WHY[10608] = "no earthquake: ComCat holds no event of M2 or more in the western US within an hour, and in central California only an M0.55 near Pacifica within 30 minutes"
KIND = {i: ("radius" if v.startswith("radius") else "box" if v.startswith("box") else "report" if v.startswith("a report") else
            "cancel" if "cancel" in v else "none") for i, v in WHY.items()}
eq = []
for r in J:
    k = CARDS[int(r["i"])]
    row = {"i": int(r["i"]), "kind": r["kind"], "code": k["c"], "w": k["w"][:150], "places": k["p"][:3], "np": len(k["p"]), "t": int(k["t"])}
    if r["kind"] == "earthquake":
        row.update({a: int(r[a]) for a in ("live", "placebo", "live_strict", "live_m45", "live_r200")})
        e = EV.get(r["event"])
        if e: row["ev"] = f'M{e["mag"]} at {e["time_utc"]}Z ({r["event"]})'
        if not row["live"]:
            assert int(r["i"]) in WHY, r["i"]
            row["why"] = WHY[int(r["i"])]; row["whyk"] = KIND[int(r["i"])]
    eq.append(row)
assert sum(1 for r in eq if r.get("live") == 0) == len(WHY) == 19
hand = []
for h in H:
    k = CARDS[int(h["i"])]
    hand.append({"kind": h["kind"], "veg": h["vegetation_fire"] == "1", "met": M[h["i"]]["met"] == "1", "code": k["c"], "w": k["w"][:140]})
D = {"res": R, "audit": {k: v for k, v in A.items() if k != "removed_ids"}, "rows": eq, "hand": hand,
     "removed_examples": [CARDS[i]["w"][:120] for i in random.Random(27).sample(A["removed_ids"], 6)]}
(HERE / "data_27.js").write_text("// generated by build_27.py; FEMA IPAWS messages and USGS ComCat records are public domain\nwindow.D27=" + json.dumps(D, separators=(",", ":")) + ";\n")
print(len(eq), sum(1 for r in eq if r.get("whyk") == "none"))
