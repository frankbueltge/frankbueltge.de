"""Study 29: writes data_29.js for the page's section #s29 from data/*_29.json and study 27's data_27.js
(the message words and places come from there, so the Studio's file is not read again).

Usage: python3 -I build_29.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
R = json.loads((HERE / "data" / "results_29.json").read_text())
A = json.loads((HERE / "data" / "alerts_29.json").read_text())
s = (HERE.parent / "s27" / "data_27.js").read_text()
D27 = json.loads(s[s.index("window.D27=") + 11:].strip().rstrip(";"))
ROWS = {r["i"]: r for r in D27["rows"] if r["kind"] == "earthquake"}
out = []
for a in A:
    r = ROWS[a["i"]]
    pts = [[m, d, k] for k, f in enumerate(a["frontiers"]) if k > 0 for (m, d) in f]
    out.append({"i": a["i"], "code": a["code"], "t": a["t"], "w": r["w"], "places": r["places"], "np": r["np"],
                "live27": a["live_27"], "strict27": a["strict_27"], "S": a["S"], "pb": a["p_best"], "pa": a["p_adj"],
                "behind": a["behind"], "best": a.get("best"), "live": a["live_events"][:60], "nlive": len(a["live_events"]),
                "plc": pts, "why27": r.get("why")})
keep = {k: R[k] for k in ("n", "K", "behind", "beside", "behind_ci", "three", "strict_27", "m5", "unmet_27_behind",
                          "unmet_27_beside", "met_27_beside", "domains", "domains_agree", "predictions", "catalogue_rows")}
if "atelier_grid" in R: keep["atelier_grid"] = {k: v for k, v in R["atelier_grid"].items() if k != "rows"}
(HERE / "data_29.js").write_text("// generated by build_29.py; FEMA IPAWS messages and USGS ComCat records are public domain\nwindow.D29="
                                 + json.dumps({"res": keep, "alerts": out}, separators=(",", ":")) + ";\n")
print(len(out), sum(len(o["plc"]) for o in out))
