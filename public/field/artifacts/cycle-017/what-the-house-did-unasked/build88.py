#!/usr/bin/env python3
"""Reading 88 (state 4, session 286): writes data88.js for the page from credit88.json, rename88.json,
literature88.json, results87.json and commits87.json. Standard library only. Run after credit88.py and rename88.py."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda f: json.load(open(os.path.join(HERE, f), encoding='utf-8'))
cr, rn, lit, r87, c87 = J('credit88.json'), J('rename88.json'), J('literature88.json'), J('results87.json'), J('commits87.json')
ARCH = lambda t: t.replace("Frank's", "the architect's").replace('Frank', 'the architect')
D87 = {(d['row'], d['n']): d for d in r87['deeds']}
C87 = {(d['row'], d['deed']): d for d in c87['deeds']}
CR = {(d['row'], d['deed']): d for d in cr['deeds']}
AUTH = [(67, 1), (132, 1), (138, 1), (149, 1), (151, 1), (169, 1)]
acts = []
for k in sorted(AUTH, key=lambda k: D87[k]['date']):
    d, c, x = D87[k], C87[k], CR[k]
    acts.append({'row': k[0], 'log_line': d['log_line'], 'date': d['date'], 'relation': d['relation'],
                 'seer': d['seer'], 'lag_log': d['lag_days'], 'found': d['found'], 'legible': d['legible'],
                 'deed_line': ARCH(d['deed_line']),
                 'commits': [[y['repo'], y['hash'], y['signer']] for y in x['deed_commits'] if y],
                 'repair': x.get('repair_hash'), 'repair_repo': x.get('repair_repo'),
                 'repair_signer': x.get('repair_signer'), 'lag_repair': x.get('lag_days'),
                 'names_deed': x.get('names_deed'), 'says_machine': x.get('says_machine')})
a2 = next(i for i in rn['items'] if i['commit'].startswith('a2ef1c1'))
data = {'reading': 88, 'session': 286, 'built': '2026-11-21', 'acts': acts,
        'found': sum(1 for d in cr['deeds'] if d['found'] == 'at its commit'), 'res': cr['results'] | {'authority': None},
        'rename': {k: rn[k] for k in ('appended_items', 'renamed', 'in_place', 'breach_changes', 'holds')} | {'a2': a2},
        'lit': [{'url': s['url'], 'cite': s['cite'], 'passage': s['passages'][-1], 'use': s['use']} for s in lit['sources']]}
with open(os.path.join(HERE, 'data88.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by build88.py from credit88.json, rename88.json, literature88.json, results87.json and commits87.json\n')
    f.write('window.DATA88=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('acts', len(acts), 'deeds in set', cr['results']['all']['deeds'])
