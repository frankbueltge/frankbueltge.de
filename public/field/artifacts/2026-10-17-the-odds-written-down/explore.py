"""Exploratory, written after the registered outcomes were read (declared in README and on the page).
Re-scores the closed windows with the circle's radius multiplied by 1, 1.5, 2 and 3 (from
data/outcomes_3x.jsonl), and writes data/explore.json and data.js, the page's data:
one row per cell [mainshock index, window index, magnitude, stated p, hit at 1x, 1.5x, 2x, 3x],
and per mainshock [id, magnitude, place, model, Mcat, radius km]."""
import json, random
F = [json.loads(l) for l in open("data/forecasts.jsonl")]
O3 = {json.loads(l)["id"]: json.loads(l) for l in open("data/outcomes_3x.jsonl")}
O1 = {json.loads(l)["id"]: json.loads(l) for l in open("data/outcomes.jsonl")}
WL = ["1 Day", "1 Week", "1 Month", "1 Year"]; MULT = [1, 1.5, 2, 3]
rows, shocks = [], []
for i, r in enumerate(F):
    mc = r["Mcat"] if r["Mcat"] is not None else 3.0
    shocks.append([r["id"], r["mag"], (r["place"] or ""), r["model"].split(" aftershock")[0].replace("Reasenberg-Jones (1989, 1994)", "R-J") +
                   " " + r["model"].split("(")[-1].rstrip(")"), mc, r["rkm"], r["time"]])
    o = O3[r["id"]]
    for w in r["windows"]:
        if w["t1"] > O1[r["id"]]["fetched"]: continue
        ev = [e for e in o["events"] if e[2] is not None and w["t0"] <= e[1] < w["t1"]]
        for b in w["bins"]:
            hits = [int(any(round(e[2], 2) >= b["M"] - 1e-9 and e[4] <= m * r["rkm"] for e in ev)) for m in MULT]
            rows.append([i, WL.index(w["label"]), b["M"], round(b["p"], 5)] + hits)
        if w["above"] is not None:
            hits = [int(any(round(e[2], 2) >= w["aboveM"] - 1e-9 and e[4] <= m * r["rkm"] for e in ev)) for m in MULT]
            rows.append([i, WL.index(w["label"]), -1, round(w["above"], 5)] + hits)   # -1 = larger than the mainshock

def oe(sel, k):
    ids = sorted({x[0] for x in sel}); by = {}
    for x in sel: by.setdefault(x[0], []).append(x)
    o = sum(x[4 + k] for x in sel); e = sum(x[3] for x in sel)
    rng = random.Random(206); R = []
    for _ in range(2000):
        s = [x for j in (rng.choice(ids) for _ in ids) for x in by[j]]
        ee = sum(x[3] for x in s); R.append(sum(x[4 + k] for x in s) / ee if ee else 0)
    R.sort()
    return {"observed": o, "expected": round(e, 2), "O_over_E": round(o / e, 3), "ci": [round(R[50], 3), round(R[1949], 3)]}

prim = [x for x in rows if x[1] == 1 and x[2] >= shocks[x[0]][4] - 1e-9]
res = {"registered_check": oe(prim, 0), "by_radius_primary": {str(m): oe(prim, k) for k, m in enumerate(MULT)},
       "by_radius_larger_1week": {str(m): {"observed": sum(x[4 + k] for x in rows if x[1] == 1 and x[2] == -1),
                                           "expected": round(sum(x[3] for x in rows if x[1] == 1 and x[2] == -1), 2)} for k, m in enumerate(MULT)},
       "primary_CA_vs_rest_at_1x": {"California": oe([x for x in prim if shocks[x[0]][2].endswith(("CA", "California", "Ridgecrest Earthquake Sequence", "California Earthquake"))], 0),
                                    "rest": oe([x for x in prim if not shocks[x[0]][2].endswith(("CA", "California", "Ridgecrest Earthquake Sequence", "California Earthquake"))], 0)}}
json.dump(res, open("data/explore.json", "w"), indent=1)
R = json.load(open("data/results.json"))
with open("data.js", "w") as fh:
    fh.write("// generated by explore.py, study 21; USGS ComCat (US government work)\n")
    fh.write("window.D=" + json.dumps({"shocks": shocks, "cells": rows, "windows": WL, "mult": MULT, "results": R, "explore": res}, separators=(",", ":")) + ";\n")
print(json.dumps(res, indent=1))
