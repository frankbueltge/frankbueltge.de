# ----------------------------------------------------------- what the page draws
def column_runs(members):
    """A layer, encoded by column: for each of the 372 slots, the runs of years
    in which that slot is contested. [slot, row0, length]"""
    s = set(members); out = []
    for slot in range(372):
        m, d = slot // 31 + 1, slot % 31 + 1
        run0, runlen = None, 0
        for row in range(NY):
            hit = idx(Y0 + row, m, d) in s
            if hit and run0 is None: run0, runlen = row, 1
            elif hit: runlen += 1
            elif run0 is not None:
                out.append([slot, run0, runlen]); run0, runlen = None, 0
        if run0 is not None: out.append([slot, run0, runlen])
    return out

