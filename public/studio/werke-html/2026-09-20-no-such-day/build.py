IDS      = [r[0] for r in READERS]
DEFAULTS = [r[0] for r in READERS if r[3]]
NAMED    = [r[0] for r in READERS if not r[3]]

cols, digests = {}, {}
for rid in IDS:
    raw = open(os.path.join(OUT, rid + ".txt"), "rb").read()
    digests[rid] = hashlib.sha256(raw).hexdigest()
    lines = raw.decode().split("\n")
    if lines and lines[-1] == "": lines.pop()
    if len(lines) != N: raise SystemExit("%s: %d lines, expected %d" % (rid, len(lines), N))
    cols[rid] = [None if x == "-" else int(x) for x in lines]

# ------------------------------------------------- what each reader does alone
taken = {}          # rid -> set of indices whose day another written date also names
per = {}
for rid, lang, call, dflt, cal in READERS:
    c = cols[rid]
    seen = Counter(v for v in c if v is not None)
    taken[rid] = set(i for i, v in enumerate(c) if v is not None and seen[v] > 1)
    refused = [i for i, v in enumerate(c) if v is None]
    runs, cur = [], []
    for i in refused:
        if cur and i == cur[-1] + 1: cur.append(i)
        else:
            if cur: runs.append(cur)
            cur = [i]
    if cur: runs.append(cur)
    # a run of refusals that is not simply the end of a short month
    reform = [r for r in runs if not all(triple(i)[2] >= 29 for i in r)]
    per[rid] = {
        "language": lang, "call": call, "is_default": dflt, "calendar": cal,
        "accepted": N - len(refused), "refused": len(refused),
        "distinct_days": len(seen),
        "answers_a_day_already_named": len(taken[rid]),
        "reform_read_off_its_own_answers": [
            {"from": iso(r[0]), "to": iso(r[-1]), "days": len(r)} for r in reform],
        "sha256_of_its_answers": digests[rid],
    }

# ------------------------------------------------------ what they do together
def state(group):
    """per written date: (n_accepting, n_distinct_days_meant)"""
    acc = [0] * N; dis = [0] * N
    for i in range(N):
        vs = [cols[r][i] for r in group]
        a = [v for v in vs if v is not None]
        acc[i] = len(a); dis[i] = len(set(a))
    return acc, dis

acc_d, dis_d = state(DEFAULTS)
acc_a, dis_a = state(IDS)

L_exist  = [i for i in range(N) if 0 < acc_d[i] < len(DEFAULTS)]
L_ident  = [i for i in range(N) if dis_d[i] > 1]
