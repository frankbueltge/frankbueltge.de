def zoom_strip(members, ya, yb, m0, m1):
    """The same layer, three months wide and nine years tall, so that the edge
    the block ends at can be read off the drawing and not only off the caption."""
    s = set(members); cw, ch, gp = 9, 17, 7
    lw, top = 44, 34
    nm = m1 - m0 + 1
    W = lw + nm * (31 * cw + gp) + 128
    Hh = top + (yb - ya + 1) * ch + 10
    p = ['<rect class="sheet" x="%d" y="%d" width="%d" height="%d"/>'
         % (lw, top, nm * (31 * cw + gp) - gp, (yb - ya + 1) * ch)]
    for k, m in enumerate(range(m0, m1 + 1)):
        x0 = lw + k * (31 * cw + gp)
        p.append('<text class="mlab" x="%d" y="%d">%s</text>' % (x0, top - 18, MONTH[m-1]))
        for dd in (1, 5, 10, 15, 20, 25, 31):
            p.append('<text class="dnum" x="%.1f" y="%d">%d</text>'
                     % (x0 + (dd - 1) * cw + cw/2, top - 5, dd))
    for y in range(ya, yb + 1):
        yy = top + (y - ya) * ch
        p.append('<text class="yr" x="%d" y="%.1f">%d</text>' % (lw - 7, yy + ch - 5, y))
        for k, m in enumerate(range(m0, m1 + 1)):
            x0 = lw + k * (31 * cw + gp)
            for dd in range(1, 32):
                if idx(y, m, dd) in s:
                    p.append('<rect class="z" x="%.1f" y="%.1f" width="%d" height="%d"/>'
                             % (x0 + (dd - 1) * cw, yy, cw, ch - 2))
    x_edge = lw + (10 - m0) * (31 * cw + gp) + 14 * cw
    y_edge = top + (1582 - ya) * ch
    p.append('<g class="lead"><line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f"/>'
             '<text x="%.1f" y="%.1f">14 October 1582 \u2014 read off the answers</text></g>'
             % (x_edge, y_edge + ch - 1, x_edge + 26, y_edge + ch + 22,
                x_edge + 29, y_edge + ch + 26))
    return ('<svg viewBox="0 0 %d %d" role="img" aria-label="the edge of the block">%s</svg>'
            % (W, Hh, "".join(p)))

# --------------------------------------------------------------- the windows
def window_svg(w):
    n = len(w["days"]); c, g = 15, 1.6
    lw, top = 178, 44
    W = lw + n * (c + g) + 66
    H = top + len(IDS) * (c + g) + 8
    p = []
    for j, ds in enumerate(w["days"]):
        x = lw + j * (c + g)
        dd = ds[8:10]
        p.append('<text class="dnum%s" x="%.1f" y="%d">%s</text>' %
                 (" nm" if ds[5:7] != w["days"][0][5:7] else "", x + c/2, top - 16, dd.lstrip("0")))
        if dd == "01" or j == 0:
            if dd == "01":
                p.append('<line class="msep" x1="%.1f" y1="%d" x2="%.1f" y2="%d"/>' %
                         (x - g/2, top - 12, x - g/2, H - 6))
            p.append('<text class="mlab" x="%.1f" y="%d">%s</text>' %
                     (x + 1, top - 30, MONTH[int(ds[5:7]) - 1]))
    p.append('<text class="mlab" x="%.1f" y="%d">the day it means by the first</text>'
             % (lw + n * (c + g) + 6, top - 16))
    for k, rid in enumerate(IDS):
        y = top + k * (c + g)
        row = w["rows"][rid]
        p.append('<text class="rl%s" x="%d" y="%.1f">%s</text>' %
                 ("" if per[rid]["is_default"] else " nm", lw - 8, y + c - 3.5, rid))
        for j, st in enumerate(row["cells"]):
            x = lw + j * (c + g)
            cls = ("no" if st == 0 else ("dup" if st == 2 else "yes"))
            p.append('<rect class="%s" x="%.1f" y="%.1f" width="%d" height="%d"/>' % (cls, x, y, c, c))
        p.append('<text class="jd" x="%.1f" y="%.1f">%s</text>' %
                 (lw + n * (c + g) + 6, y + c - 3.5,
                  row["first_day_meant"] if row["first_day_meant"] else "—"))
    return '<svg viewBox="0 0 %d %d" role="img" aria-label="%s">%s</svg>' % (W, H, w["title"], "".join(p))

