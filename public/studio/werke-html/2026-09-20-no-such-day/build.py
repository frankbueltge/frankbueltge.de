reform_contested = sorted(ex & set(REFORM_DATES))
strict_contested = sorted(ex - set(REFORM_DATES))
by_slot = Counter((triple(i)[1], triple(i)[2]) for i in strict_contested)

# the identity-contested span, read off the answers and not off any documentation
span = (iso(L_ident[0]), iso(L_ident[-1])) if L_ident else None
span_is_closed = bool(L_ident) and L_ident[-1] - L_ident[0] + 1 == len(L_ident)

