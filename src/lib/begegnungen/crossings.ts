/** Never throws, never guesses: an id it does not know comes back as `unknown`, and callers
 *  print the raw string beside it. */
export function normaliseVoice(raw: unknown): VoiceId {
  if (typeof raw !== 'string') return 'unknown'
  return VOICE_ALIASES[raw.trim().toLowerCase()] ?? 'unknown'
}

export function voiceOf(raw: unknown): Voice {
  return VOICES[normaliseVoice(raw)]
}

// ————————————————————————————————————————————————— reading guards ———————————

const str = (v: unknown): string | null => {
  if (typeof v !== 'string') return null
  const t = v.trim()
  return t === '' ? null : t
}

const asArray = (v: unknown): unknown[] => (Array.isArray(v) ? v : [])

const obj = (v: unknown): Record<string, unknown> =>
  v !== null && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : {}

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/
const isoDate = (v: unknown): string | null => {
  const s = str(v)
  return s && ISO_DATE.test(s) ? s : null
}

// ————————————————————————————————————————————————— standing —————————————————

/** Where a crossing stands. `unstated` is a real third value and not a bug: two of the five
 *  recorded encounters carry `status: null`, and calling those "concluded" would close a
 *  crossing the register never closed. */
export type Standing = 'open' | 'concluded' | 'unstated'

const CONCLUDED = /\b(closed|concluded|resolved|complete[d]?|settled|withdrawn|abandoned|archived)\b/i
const OPEN = /\b(open|standing|running|active|unresolved|ongoing|review|waiting|pending)\b/i

/**
 * Derived from the record's own status words — and ONLY from its LEADING CLAUSE, which is where
 * the register states a standing. Its own format is `<standing> — <what has happened since>`,
 * and the second half runs to several hundred words on the newer encounters.
 *
 * That distinction is not fastidious, it is a bug this rule was written to fix. The first draft
 * scanned the whole string, and enc-2026-004 — whose status line opens `open/standing —` and then
 * reports, forty words later, that a source premiere "was KILLED/WITHDRAWN at source" — was filed
 * as CONCLUDED. The encounter is open; a thing INSIDE it was withdrawn. A page that closes a
 * crossing because of a word in its contents is reporting the opposite of the record.
 *
 * Where the leading clause carries no status word at all, the whole line is read rather than the
 * crossing being called unstated on a formatting technicality. Nothing is invented, and silence
 * is never read as a conclusion: no status is `unstated`, which is a third value on purpose.
 */
export function standingOf(statusText: string | null | undefined): Standing {
  const s = (statusText ?? '').trim()
  if (s === '') return 'unstated'
  const head = s.split(/[—–]/)[0].trim() || s
  const read = (t: string): Standing | null =>
    CONCLUDED.test(t) ? 'concluded' : OPEN.test(t) ? 'open' : null
  return read(head) ?? read(s) ?? 'unstated'
}

// ————————————————————————————————————————————————— quoted spans —————————————

export interface Quoted {
  /** the record's words, verbatim */
  text: string
  /** the path the words were read from — printed with the quote */
  source: string
  /** which field of the record it is, in the record's own vocabulary */
  label: string
}

const quoted = (text: string | null, source: string, label: string): Quoted | null =>
  text ? { text, source, label } : null

// ————————————————————————————————————————————————— attachment rules —————————

/**
 * WHICH RULE PUT A ROW ON A CROSSING. Every row prints its rule, so a visitor can see what
 * kind of evidence they are looking at instead of taking the arrangement on trust. The rules
 * are deliberately few and every one of them is EXPLICIT — a record naming the thing itself.
 * There is no "the prose mentions it" rule anywhere in this module; that was considered and
 * rejected for the same reason the studio's dossier rejected it (a house's own words about
 * the world are not a claim about another house).
 */
export type AttachmentRule =
  | 'ledger-event'
  | 'ledger-obligation'
  | 'ledger-non-participation'
  | 'register-status'
  | 'narrated-station'
  | 'ji-commitment'
  | 'ji-status'

/** Each label completes the sentence "attached by …", which is how the page prints it. */
export const CROSSING_RULE_LABELS: Record<AttachmentRule, string> = {
  'ledger-event': 'the encounter ledger’s own dated event',
  'ledger-obligation': 'an obligation the ledger records as still standing',
  'ledger-non-participation': 'the ledger’s own note of a documented non-relation',
  'register-status': 'the register’s own status line for this encounter',
  'narrated-station':
    'the contact zone’s own narrated station for this encounter — its editorial layer, named as such',
  'ji-commitment': 'the practice’s own Local Commitment to this inquiry',
  'ji-status': 'the practice’s own status note on its commitment',
}

export interface CrossingRow {
  /** the record's date, or null where it states none */
  date: string | null
  voice: VoiceId
  /** the raw participant id, printed where the voice is unknown to this site */
  rawVoice: string | null
  /** what the record calls this move, in its own vocabulary */
  label: string
  /** the record's words, verbatim */
  text: string
  /** an attribution the record itself carries for the quote, verbatim; null where it has none */
  attribution: string | null
  source: string
  by: AttachmentRule
}

// ————————————————————————————————————————————————— the crossing —————————————

export interface CrossingVoice {
  voice: VoiceId
  rawVoice: string
  /** the record's own word for what this voice is doing here (`source`, `receiver`,
   *  `conductor`, `ACTIVE`, `COMPLETED` …) — never a word written on this site */
  role: string | null
  /** the voice's own account of where it stands, verbatim, or null */
  localStatus: Quoted | null
  /** joint inquiries only: the question this voice posed under its own protocol, verbatim */
  localQuestion: Quoted | null
  /** joint inquiries only: the first claim of its answer, verbatim */
  headlineClaim: Quoted | null
  /** joint inquiries only: what it shipped, and where */
  output: { title: string; url: string } | null
}

export interface CrossingSource {
  path: string
  note: string
}

/** Two readings of one thing, both kept. Preserved dissent is an invariant of this ecology —
 *  the ledger records it as a first-class object precisely so no surface can quietly resolve
 *  it, and this dossier prints both sides side by side with the record's own closing line. */
export interface CrossingDivergence {
  leftLabel: string
  leftQuote: string
  leftVoice: VoiceId
  rightLabel: string
  rightQuote: string
  rightVoice: VoiceId
  closing: string | null
  source: string
}

export interface Crossing {
  kind: 'joint-inquiry' | 'encounter'
  id: string
  /** the deep-link anchor and dom id fragment: `crossing-<anchor>` */
  anchor: string
  /** every id another record might name this crossing by, lowercased — the register writes an
   *  encounter's full id, the practices' own records write the short one */
  matchIds: string[]
  title: string
  /** joint inquiries: the shared question the constellation was formed around, verbatim */
  question: Quoted | null
  standing: Standing
  /** the record's own status words, verbatim */
  status: Quoted | null
  asOf: string | null
  /** the newest date anywhere in the crossing's own record — the honest "is this alive" */
  lastMove: string | null
  recordUrl: string | null
  voices: CrossingVoice[]
  rows: CrossingRow[]
  sources: CrossingSource[]
  /** ledger exports only: what the record says did NOT happen, and why that is not a failure */
  nonParticipation: { voice: VoiceId; rawVoice: string; note: string; source: string }[]
  /** two readings the record refuses to resolve into one, where it records such a pair */
  divergence: CrossingDivergence | null
}

