/** One row of `src/data/begegnungen/register.json`. Every field optional on purpose: the
 *  register grew a structured `status` object in late July and older entries still carry
 *  `null`, so both shapes have to read without a branch in the template. */
export interface RegisterInput {
  encounter_id?: unknown
  title?: unknown
  status?: unknown
  approval?: unknown
  authored_by?: unknown
  participants?: unknown
  record_url?: unknown
  observed?: unknown
}

/** The ledger projection `src/data/begegnungen/<slug>/score.json` — present for the
 *  encounters the contact zone has exported, absent for the rest. */
export interface LedgerInput {
  encounter_id?: unknown
  headline?: unknown
  status?: unknown
  participants?: unknown
  non_participants?: unknown
  events?: unknown
  obligations?: unknown
  divergence?: unknown
}

/** The contact zone's narrated entrance for ONE encounter (`src/data/begegnungen/entrance.json`).
 *  It is an EDITORIAL layer over the same ledger — it gives each station a heading in the
 *  narrator's words and, occasionally, quotes a span the event payload does not isolate. It is
 *  read because those headings are the most readable labels the record carries, and it is
 *  labelled as editorial wherever it appears, never blended into the practices' own words. */
export interface NarrativeInput {
  encounter_id?: unknown
  authored_by?: unknown
  approval?: unknown
  stations?: unknown
}

const REGISTER_SOURCE = 'src/data/begegnungen/register.json'
const NARRATIVE_SOURCE = 'src/data/begegnungen/entrance.json'

/** `enc-2026-005-atlas-lent-not-lifted` → `enc-2026-005`. The same derivation
 *  research-ecology's export uses for the folder name (`shortEncounterSlug`). */
export function encounterSlug(encounterId: string): string {
  return encounterId.split('-').slice(0, 3).join('-')
}

/** The register's `status` in both shapes it has had: a bare string, and the object it became
 *  in late July. Neither is normalised into the other — the page prints what it finds. */
function readRegisterStatus(v: unknown): { statusLine: string | null; asOf: string | null } {
  const s = str(v)
  if (s) return { statusLine: s, asOf: null }
  const rec = obj(v)
  return { statusLine: str(rec.statusLine), asOf: isoDate(rec.as_of) }
}

export function buildEncounter(
  input: RegisterInput,
  ledgerInput?: LedgerInput,
  narrativeInput?: NarrativeInput,
): Crossing | null {
  const raw = obj(input) as RegisterInput
  const ledger = ledgerInput === undefined ? undefined : (obj(ledgerInput) as LedgerInput)
  const id = str(raw.encounter_id)
  if (!id) return null
  const slug = encounterSlug(id)
  const ledgerSource = `src/data/begegnungen/${slug}/score.json`
  const { statusLine, asOf } = readRegisterStatus(raw.status)

  // Voices: the register names them; where a ledger export exists it names them too, with the
  // practice's own account of what it did. The register is the spine (it covers every
  // encounter), the ledger fills in — never the other way round, so one uniform rule holds.
  const ledgerParticipants = new Map<string, Record<string, unknown>>()
  for (const p of asArray(ledger?.participants)) {
    const rec = obj(p)
    const key = str(rec.collective_id) ?? str(rec.actor_id)
    if (key) ledgerParticipants.set(key, rec)
  }

  const voices: CrossingVoice[] = []
  for (const p of asArray(raw.participants)) {
    const rec = obj(p)
    const rawVoice = str(rec.id) ?? ''
    if (!rawVoice) continue
    const fromLedger = ledgerParticipants.get(rawVoice)
    voices.push({
      voice: normaliseVoice(rawVoice),
      rawVoice,
      role: str(rec.role),
      localStatus: quoted(
        fromLedger ? str(fromLedger.local_status) : null,
        ledgerSource,
        'its own account of what it did here',
      ),
      localQuestion: null,
      headlineClaim: null,
      output: null,
    })
  }

  // The narrated stations, where the contact zone has written them for THIS encounter. Used
  // twice below: a station's heading becomes the label of the ledger event it narrates (the
  // narrator's words for what the move was, instead of the raw `offer.answered`), and a station
  // whose quote the event payload does not isolate becomes a row of its own, under its own rule.
  const stations = str(obj(narrativeInput).encounter_id) === id ? asArray(obj(narrativeInput).stations) : []
  const stationHeading = new Map<string, string>()
  for (const stRaw of stations) {
    const st = obj(stRaw)
    const evt = str(st.akte_event_id)
    const heading = str(st.heading)
    if (evt && heading && !stationHeading.has(evt)) stationHeading.set(evt, heading)
  }

  // The chronology: the ledger's own dated events, verbatim, each with the attribution the
  // ledger itself carries. An encounter without an export has none, and says so.
  const rows: CrossingRow[] = []
  const ledgerQuotes = new Set<string>()
  for (const e of asArray(ledger?.events)) {
    const rec = obj(e)
    const text = str(rec.quote)
    if (!text) continue // an event with no isolated quote is a row this site would have to write
    const issuer = obj(rec.issuer)
    const rawVoice = str(rec.lane) ?? str(issuer.collective_id) ?? str(issuer.actor_id) ?? ''
    ledgerQuotes.add(text)
    const eventId = str(rec.event_id)
    rows.push({
      date: isoDate(rec.date),
      voice: normaliseVoice(rawVoice),
      rawVoice: rawVoice || null,
      label: (eventId ? stationHeading.get(eventId) : null) ?? str(rec.event_type) ?? 'event',
      text,
      attribution: str(rec.attribution),
      source: ledgerSource,
      by: 'ledger-event',
    })
  }

  // A station the ledger's own event payload does not isolate a quote for. Not a duplicate and
  // not a gap-filler: it is a span of the record the events skip, and it says whose layer it is.
  for (const stRaw of stations) {
    const st = obj(stRaw)
    const text = str(st.quote)
    if (!text || ledgerQuotes.has(text)) continue
    rows.push({
      date: null,
      voice: 'conductor',
      rawVoice: str(obj(narrativeInput).authored_by),
      label: str(st.heading) ?? 'station',
      text,
      attribution: str(st.attribution),
      source: NARRATIVE_SOURCE,
      by: 'narrated-station',
    })
  }

  for (const o of asArray(ledger?.obligations)) {
    const rec = obj(o)
    const text = str(rec.clause_text)
    if (!text) continue
    const rawVoice = str(rec.lane) ?? ''
    rows.push({
      date: null,
      voice: normaliseVoice(rawVoice),
      rawVoice: rawVoice || null,
      label: str(rec.label) ?? 'obligation',
      text,
      attribution: str(rec.status) ? `obligation ${str(rec.status)}` : null,
      source: ledgerSource,
      by: 'ledger-obligation',
    })
  }

  // The register's own status line is itself a dated statement about the crossing, and for
  // three of the five encounters it is the ONLY prose the record carries. It goes in as a row
  // under its own rule rather than being quietly promoted into the chronology.
  if (statusLine) {
    rows.push({
      date: asOf,
      voice: 'conductor',
      rawVoice: str(raw.authored_by),
      label: 'the register’s standing',
      text: statusLine,
      attribution: str(raw.approval) ? `wording ${str(raw.approval)}` : null,
      source: REGISTER_SOURCE,
      by: 'register-status',
    })
  }

  const nonParticipation = asArray(ledger?.non_participants).flatMap((n) => {
    const rec = obj(n)
    const rawVoice = str(rec.collective_id) ?? ''
    const note = str(rec.note)
    return note ? [{ voice: normaliseVoice(rawVoice), rawVoice, note, source: ledgerSource }] : []
  })

  // Preserved dissent, where the ledger records it. Both sides or neither: a divergence with
  // one half quoted would be the resolution the record refused to make.
  const dv = obj(ledger?.divergence)
  const leftQuote = str(dv.leftQuote)
  const rightQuote = str(dv.rightQuote)
  const divergence: CrossingDivergence | null =
    leftQuote && rightQuote
      ? {
          leftLabel: str(dv.leftLabel) ?? 'one reading',
          leftQuote,
          leftVoice: normaliseVoice(dv.leftLane),
          rightLabel: str(dv.rightLabel) ?? 'the other reading',
          rightQuote,
          rightVoice: normaliseVoice(dv.rightLane),
          closing: str(dv.closing),
          source: ledgerSource,
        }
      : null

  const ledgerStatus = readRegisterStatus(ledger?.status)
  const dates = [asOf, ledgerStatus.asOf, ...rows.map((r) => r.date)]
    .filter((d): d is string => d !== null)
    .sort()

  const sources: CrossingSource[] = [
    { path: REGISTER_SOURCE, note: 'the register of recorded encounters, exported by the contact zone' },
  ]
  if (ledger) {
    sources.push({ path: ledgerSource, note: 'this encounter’s own ledger projection — every event, dated, as it was filed' })
  }
  if (stations.length > 0) {
    sources.push({ path: NARRATIVE_SOURCE, note: 'the contact zone’s narrated stations for this encounter — its editorial layer over the same ledger' })
  }

  return {
    kind: 'encounter',
    id,
    anchor: slug,
    matchIds: [...new Set([id.toLowerCase(), slug.toLowerCase()])],
    title: str(raw.title) ?? str(ledger?.headline) ?? id,
    question: null,
    standing: standingOf(statusLine),
    status: quoted(statusLine, REGISTER_SOURCE, 'the register’s own status line'),
    asOf: asOf ?? ledgerStatus.asOf,
    lastMove: dates.at(-1) ?? null,
    recordUrl: str(raw.record_url),
    voices,
    rows: sortRows(rows),
    sources,
    nonParticipation,
    divergence,
  }
}

// ————————————————————————————————————————————————— ordering —————————————————

/** Newest first, and a row the record left undated sorts last rather than to 1970 — an
 *  obligation states no date because it is still standing, not because it is old. */
export function sortRows(rows: readonly CrossingRow[]): CrossingRow[] {
  return [...rows].sort((a, b) => {
    if (a.date && b.date && a.date !== b.date) return b.date.localeCompare(a.date)
    if (a.date && !b.date) return -1
    if (!a.date && b.date) return 1
    return 0
  })
}

const STANDING_ORDER: Record<Standing, number> = { open: 0, unstated: 1, concluded: 2 }

/**
 * The order the page reads in: what is still open leads, and inside each group the crossing
 * that moved most recently leads. Joint inquiries sort ahead of encounters at equal standing
 * and equal date — the shared question is the thing the practices are doing together NOW,
 * and an encounter of the same day is its context.
 */
export function sortCrossings(crossings: readonly Crossing[]): Crossing[] {
  return [...crossings].sort(
    (a, b) =>
      STANDING_ORDER[a.standing] - STANDING_ORDER[b.standing] ||
      (b.lastMove ?? '').localeCompare(a.lastMove ?? '') ||
      (a.kind === b.kind ? 0 : a.kind === 'joint-inquiry' ? -1 : 1) ||
      a.id.localeCompare(b.id),
  )
}

export interface CrossingsInput {
  inquiries: readonly JointInquiryInput[]
  register: readonly RegisterInput[]
  /** ledger projections keyed by their short slug (`enc-2026-005`) — the two the contact zone
   *  has exported today, more when it exports more */
  ledgers: Readonly<Record<string, LedgerInput>>
  /** the narrated entrance, which the export writes for exactly one encounter at a time */
  narrative?: NarrativeInput
}

export function buildCrossings(input: CrossingsInput): Crossing[] {
  const jis = asArray(input.inquiries)
    .map((ji) => buildJointInquiry(obj(ji)))
    .filter((c): c is Crossing => c !== null)
  const encounters = asArray(input.register)
    .map((e) => {
      const rec = obj(e) as RegisterInput
      const id = str(rec.encounter_id)
      const ledger = id ? (obj(input.ledgers)[encounterSlug(id)] as LedgerInput | undefined) : undefined
      return buildEncounter(rec, ledger, input.narrative)
    })
    .filter((c): c is Crossing => c !== null)
  return sortCrossings([...jis, ...encounters])
}

/** The page's protagonist: the open crossing that moved most recently — a joint inquiry where
 *  one is open, because `sortCrossings` puts it there. Where nothing is open, the newest
 *  crossing of any standing leads, which is still the honest answer to "what is happening". */
export function leadCrossing(crossings: readonly Crossing[]): Crossing | undefined {
  return crossings[0]
}

/** Every voice that appears in any crossing, in the order the recorded quartet is written.
 *  Used for the page's legend — a colour is only ever explained where it is used. */
export function crossingVoices(crossings: readonly Crossing[]): Voice[] {
  const order: VoiceId[] = ['ulysses', 'meridian', 'ensemble', 'plenum', 'mrr', 'datavism', 'conductor', 'unknown']
  const seen = new Set<VoiceId>()
  for (const c of crossings) {
    for (const v of c.voices) seen.add(v.voice)
    for (const r of c.rows) seen.add(r.voice)
  }
  return order.filter((id) => seen.has(id)).map((id) => VOICES[id])
}
