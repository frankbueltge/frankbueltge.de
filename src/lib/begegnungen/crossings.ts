/** The shape `scripts/ecology/sync-joint-inquiries.mjs` writes. Everything optional, because
 *  the fixture it mirrors is the contact zone's and can grow a field any night. */
export interface JointInquiryInput {
  inquiry_id?: unknown
  slug?: unknown
  title?: unknown
  status?: unknown
  public_summary?: unknown
  initiated_by?: unknown
  coordination_profile?: unknown
  created_at?: unknown
  updated_at?: unknown
  record_url?: unknown
  source_commit?: unknown
  participants?: unknown
}

const JI_SOURCE = 'src/data/begegnungen/joint-inquiries.json'

export function buildJointInquiry(input: JointInquiryInput): Crossing | null {
  const raw = obj(input) as JointInquiryInput
  const id = str(raw.inquiry_id)
  if (!id) return null
  const title = str(raw.title) ?? id
  const statusWord = str(raw.status)
  const anchor = str(raw.slug) ?? id

  const voices: CrossingVoice[] = []
  const rows: CrossingRow[] = []

  for (const p of asArray(raw.participants)) {
    const rec = obj(p)
    const rawVoice = str(rec.practice_id) ?? ''
    const voice = normaliseVoice(rawVoice)
    const issuedAt = isoDate(rec.issued_at)
    const localQuestion = str(rec.local_question)
    const headlineClaim = str(rec.headline_claim)
    const statusNote = str(rec.local_status_note)
    const outputTitle = str(rec.output_title)
    const outputUrl = str(rec.output_url)
    // The practice's OWN record, where the fixture carries the pointer — printed instead of
    // the mirror's path, because that is where the words were written.
    const own = str(rec.source_uri) ?? JI_SOURCE

    voices.push({
      voice,
      rawVoice,
      role: str(rec.commitment_status) ?? str(rec.local_status),
      localStatus: quoted(statusNote, own, 'its own status note'),
      localQuestion: quoted(localQuestion, own, 'the question it posed under its own protocol'),
      headlineClaim: quoted(headlineClaim, own, 'the first claim of its answer'),
      output: outputTitle && outputUrl ? { title: outputTitle, url: outputUrl } : null,
    })

    if (localQuestion) {
      rows.push({
        date: issuedAt,
        voice,
        rawVoice: rawVoice || null,
        label: 'Local Commitment',
        text: localQuestion,
        attribution: str(rec.commitment_status),
        source: own,
        by: 'ji-commitment',
      })
    }
    if (statusNote) {
      rows.push({
        date: issuedAt,
        voice,
        rawVoice: rawVoice || null,
        label: str(rec.local_status) ?? 'status',
        text: statusNote,
        attribution: null,
        source: own,
        by: 'ji-status',
      })
    }
  }

  const dates = [isoDate(raw.created_at), isoDate(raw.updated_at), ...rows.map((r) => r.date)]
    .filter((d): d is string => d !== null)
    .sort()

  return {
    kind: 'joint-inquiry',
    id,
    anchor,
    matchIds: [id.toLowerCase()],
    title,
    question: quoted(str(raw.public_summary), JI_SOURCE, 'the shared question, as the contact zone constituted it'),
    standing: standingOf(statusWord),
    status: quoted(statusWord, JI_SOURCE, 'the inquiry’s own status'),
    asOf: isoDate(raw.updated_at),
    lastMove: dates.at(-1) ?? null,
    recordUrl: str(raw.record_url),
    voices,
    rows: sortRows(rows),
    sources: [
      { path: JI_SOURCE, note: 'the register of shared questions, mirrored from the contact zone’s own fixture' },
      ...[...new Set(voices.map((v) => v.localStatus?.source ?? v.localQuestion?.source).filter((s): s is string => !!s && s !== JI_SOURCE))].map(
        (path) => ({ path, note: 'the practice’s own record of its commitment' }),
      ),
    ],
    nonParticipation: [],
    divergence: null,
  }
}

