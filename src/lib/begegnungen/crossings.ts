// src/lib/begegnungen/crossings.ts — the crossings: what the practices are doing WITH each
// other, read out of the records that say so.
//
// WHY THIS EXISTS. /encounters used to lead with two large drawings of five completed
// encounters — the contact zone told retrospectively, while the living thing between the
// practices (a joint inquiry three of them are answering in parallel) had no page at all.
// Every other room now leads with its current protagonist. This module supplies The Middle's:
// the CROSSINGS, joint inquiries and encounters together, one ordered list, the open ones
// first.
//
// THE HOUSE RULE HOLDS THROUGHOUT: nothing here is written, summarised or rounded. Every
// string this module returns is a span of a committed file, carried with the path it came
// from and with the RULE that attached it, so a reader can check the attribution instead of
// trusting it. Where a record states nothing, this returns null and the page says so in
// words.
//
// PURE BY CONSTRUCTION. No import.meta.glob, no fs — callers hand over already-imported JSON,
// so this module is unit-testable against fixtures AND against the real committed exports.
//
// DEFENSIVE BY OBLIGATION. Its inputs are regenerated by an export chain that runs after
// every engine session; a shape that changes overnight must degrade to "the record states
// none", never to a build failure. Hence: every field is read through a guard, every array
// through `asArray`, and no function in this file throws.

